-- Document stats schema (PostgreSQL 16).
-- CPU-heavy workload: the database only returns a document's text; a cache
-- miss costs computing its stats (word counts, top words, readability), not
-- a big query. Both app instances behind Nginx share this one database, which
-- is separate from the Twitter clone's.
--
-- Ids are dense and sequential so block keys can be computed as
-- block:{id / size} (RQ3).
--
-- Edits (PUT /documents/{id}) are the writes. version increases on every
-- edit: stats computed from an older version are a stale read (RQ2). k6
-- records the version each acknowledged edit returned; after a crash test,
-- lost writes = acknowledged versions higher than the version stored here.

CREATE TABLE documents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200) NOT NULL,
    content    TEXT         NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
