-- Monte Carlo option pricer schema (PostgreSQL 16).
-- CPU-heavy workload: the database only holds small inputs; a cache miss
-- costs a Monte Carlo simulation (many random price paths), not a big query.
-- Both app instances behind Nginx share this one database, which is separate
-- from the Twitter clone's.

-- Assets --------------------------------------------------------------------
-- The underlyings. Market updates (POST /assets/{id}/price) are the writes:
-- each one changes the inputs of every option on that asset.
--
-- version increases on every update. A cached price computed from an older
-- version is a stale read (RQ2). k6 records the version each acknowledged
-- update returned; after a crash test, lost writes = acknowledged versions
-- higher than the version stored here.
--
-- fillfactor leaves room on each page so frequent price updates can be HOT
-- updates (no index writes).

CREATE TABLE assets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol      VARCHAR(16)      NOT NULL UNIQUE,
    spot_price  DOUBLE PRECISION NOT NULL CHECK (spot_price > 0),
    volatility  DOUBLE PRECISION NOT NULL CHECK (volatility > 0),  -- annualised sigma
    risk_free   DOUBLE PRECISION NOT NULL DEFAULT 0.03,             -- annualised rate
    version     BIGINT           NOT NULL DEFAULT 1,
    updated_at  TIMESTAMPTZ      NOT NULL DEFAULT now()
) WITH (fillfactor = 80);

-- Options -------------------------------------------------------------------
-- The cached items (the "tweets" of this app). Many contracts per asset, far
-- more than fit in the cache. Ids are dense and sequential so block keys can
-- be computed as block:{id / size} (RQ3); seed data orders them by asset so
-- a block holds related contracts.
--
-- style decides how heavy a simulation is: path-dependent options (asian,
-- barrier) simulate every time step, european only needs the final price.

CREATE TYPE option_kind  AS ENUM ('call', 'put');
CREATE TYPE option_style AS ENUM ('european', 'asian', 'barrier');

CREATE TABLE options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id    BIGINT           NOT NULL REFERENCES assets (id) ON DELETE CASCADE,
    kind        option_kind      NOT NULL,
    style       option_style     NOT NULL,
    strike      DOUBLE PRECISION NOT NULL CHECK (strike > 0),
    barrier     DOUBLE PRECISION CHECK (barrier > 0),
    maturity    DOUBLE PRECISION NOT NULL CHECK (maturity > 0),     -- years
    paths       INTEGER          NOT NULL CHECK (paths > 0),        -- simulation size
    steps       INTEGER          NOT NULL CHECK (steps > 0),        -- time steps per path
    seed        BIGINT           NOT NULL,                          -- fixed RNG seed, reproducible prices
    CHECK ((style = 'barrier') = (barrier IS NOT NULL))
);

-- Invalidation and write-through: find every option on an updated asset.
CREATE INDEX idx_options_asset ON options (asset_id);

-- Option prices -------------------------------------------------------------
-- The latest computed price per option: the backing store that write-through
-- and write-back persist to, and what lets the app skip a re-simulation when
-- the cache misses but the stored price is still current.
--
-- asset_version records which asset version the price was computed from;
-- comparing it with assets.version tells whether the price is stale.

CREATE TABLE option_prices (
    option_id     BIGINT           PRIMARY KEY REFERENCES options (id) ON DELETE CASCADE,
    price         DOUBLE PRECISION NOT NULL,
    std_error     DOUBLE PRECISION NOT NULL,
    asset_version BIGINT           NOT NULL,
    compute_ms    DOUBLE PRECISION NOT NULL,   -- simulation time, the miss penalty
    computed_at   TIMESTAMPTZ      NOT NULL DEFAULT now()
) WITH (fillfactor = 80);
