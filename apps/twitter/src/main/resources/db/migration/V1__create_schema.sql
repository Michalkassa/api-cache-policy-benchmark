-- Twitter clone schema (PostgreSQL 16).
-- Both app instances behind Nginx share this one database.

-- Users ---------------------------------------------------------------------

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(32)  NOT NULL UNIQUE,
    display_name VARCHAR(64)  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Follows -------------------------------------------------------------------
-- The primary key (follower_id, followee_id) serves the timeline lookup
-- "who does this user follow?".

CREATE TABLE follows (
    follower_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    followee_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CHECK (follower_id <> followee_id)
);

CREATE INDEX idx_follows_followee ON follows (followee_id);

-- Tweets --------------------------------------------------------------------
-- Ids are dense and sequential so block keys can be computed as
-- block:{id / size} (RQ3).
--
-- like_count is denormalised: it is the value that gets cached, updated by
-- the write policies (RQ2) and checked for stale reads.
--
-- fillfactor leaves room on each page so like_count updates can be HOT
-- updates (no index writes), keeping write cost low for viral tweets.

CREATE TABLE tweets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reply_to_id BIGINT       REFERENCES tweets (id) ON DELETE CASCADE,
    content     VARCHAR(280) NOT NULL,
    like_count  INTEGER      NOT NULL DEFAULT 0 CHECK (like_count >= 0),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
) WITH (fillfactor = 90);

-- GET /timeline: newest top-level tweets per followed author.
CREATE INDEX idx_tweets_author_created
    ON tweets (author_id, created_at DESC, id DESC)
    WHERE reply_to_id IS NULL;

-- GET /tweets/{id}: replies to a tweet, oldest first.
CREATE INDEX idx_tweets_reply_to_created
    ON tweets (reply_to_id, created_at, id)
    WHERE reply_to_id IS NOT NULL;

-- Likes ---------------------------------------------------------------------
-- One row per (user, tweet), so a repeated like is idempotent.
-- After a crash test, lost writes = acknowledged likes missing from this
-- table, or a like_count that no longer matches the row count.

CREATE TABLE likes (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tweet_id   BIGINT      NOT NULL REFERENCES tweets (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, tweet_id)
);

CREATE INDEX idx_likes_tweet ON likes (tweet_id);
